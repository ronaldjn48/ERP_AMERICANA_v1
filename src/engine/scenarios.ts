function defaults(partial: Omit<Decisions, 'automation' | 'loanDraw' | 'loanRepay' | 'eventChoice' | 'uxInvestment'> & {
  reorderPoint: number;
  reorderQty: number;
}): Decisions {
  const { reorderPoint, reorderQty, ...rest } = partial;
  return {
    ...rest,
    uxInvestment: 0,
    automation: { ...baseAutomation, reorderPoint, reorderQty },
    loanDraw: 0,
    loanRepay: 0,
    eventChoice: null,
  };
}

